TECH_LABELS = [k for k in LEXICON if k.startswith("TECH_") or k == "AI_ENGINEERING"]
PRODUCT_LABELS = [k for k in LEXICON if k.startswith("PRODUCT_")]
APP_LABELS = [k for k in LEXICON if k.startswith("APP_")]


def flat():
    """展平为 (keyword, label, name_cn, tier) 四元组列表"""
    rows = []
    for lab, d in LEXICON.items():
        for tier in ("core", "ext"):
            for kw in d[tier]:
                rows.append({
                    "keyword": kw,
                    "label": lab,
                    "direction_cn": d["name_cn"],
                    "layer": ("TECH" if lab in TECH_LABELS
                              else "PRODUCT" if lab in PRODUCT_LABELS else "APP"),
                    "cluster": CLUSTER.get(lab, ""),
                    "tier": "CORE" if tier == "core" else "EXT",
                    "lang": ("EN" if kw.isascii() else
                             "MIX" if any(c.isascii() and c.isalpha() for c in kw) else "ZH"),
                })
    return rows


